#!/usr/bin/env python3
"""Generate src/irc/vectors.rs from the ircdocs parser-tests (CC0).

Usage: python3 tools/gen_parser_vectors.py [PARSER_TESTS_DIR]

The default directory is the local standards library's clone. The vectors
become Rust constants so tests need no YAML parser. Needs PyYAML.
"""

import subprocess
import sys
from pathlib import Path

import yaml

SOURCE = Path(sys.argv[1] if len(sys.argv) > 1 else
              "/big/web-standards/repositories/ircdocs/parser-tests")
OUTPUT = Path(__file__).resolve().parent.parent / "src" / "irc" / "vectors.rs"


def rust_str(value):
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    return '"' + "".join(out) + '"'


def opt(value):
    return "None" if value is None else "Some(%s)" % rust_str(value)


def strs(values):
    return "&[" + ", ".join(rust_str(v) for v in values) + "]"


def tags(mapping):
    if not mapping:
        return "&[]"
    return "&[" + ", ".join("(%s, %s)" % (rust_str(k), rust_str(v or "")) for k, v in mapping.items()) + "]"


def load(name):
    with open(SOURCE / "tests" / name, encoding="utf-8") as f:
        return yaml.safe_load(f)["tests"]


commit = subprocess.run(["git", "-C", str(SOURCE), "rev-parse", "HEAD"],
                        capture_output=True, text=True).stdout.strip() or "unknown"
lines = [
    "//! Conformance vectors from ircdocs/parser-tests (CC0), commit",
    "//! `%s`." % commit,
    "//! Generated by `tools/gen_parser_vectors.py`; do not edit by hand.",
    "",
    "#![allow(clippy::all)]",
    "",
    "/// A line and the parts it must split into (`msg-split.yaml`).",
    "pub struct Split {",
    "    pub input: &'static str,",
    "    pub tags: &'static [(&'static str, &'static str)],",
    "    pub source: Option<&'static str>,",
    "    pub verb: &'static str,",
    "    pub params: &'static [&'static str],",
    "}",
    "",
    "/// Parts and the lines they may join into (`msg-join.yaml`).",
    "pub struct Join {",
    "    pub desc: &'static str,",
    "    pub tags: &'static [(&'static str, &'static str)],",
    "    pub source: Option<&'static str>,",
    "    pub verb: &'static str,",
    "    pub params: &'static [&'static str],",
    "    pub matches: &'static [&'static str],",
    "}",
    "",
    "/// A source and its nick, user and host (`userhost-split.yaml`).",
    "pub struct UserHost {",
    "    pub source: &'static str,",
    "    pub nick: &'static str,",
    "    pub user: Option<&'static str>,",
    "    pub host: Option<&'static str>,",
    "}",
    "",
    "pub const SPLIT: &[Split] = &[",
]
for test in load("msg-split.yaml"):
    atoms = test["atoms"]
    lines.append("    Split { input: %s, tags: %s, source: %s, verb: %s, params: %s }," % (
        rust_str(test["input"]), tags(atoms.get("tags")), opt(atoms.get("source")),
        rust_str(atoms["verb"]), strs(atoms.get("params", []))))
lines += ["];", "", "pub const JOIN: &[Join] = &["]
for test in load("msg-join.yaml"):
    atoms = test["atoms"]
    lines.append("    Join { desc: %s, tags: %s, source: %s, verb: %s, params: %s, matches: %s }," % (
        rust_str(test.get("desc", "")), tags(atoms.get("tags")), opt(atoms.get("source")),
        rust_str(atoms["verb"]), strs(atoms.get("params", [])), strs(test["matches"])))
lines += ["];", "", "pub const USERHOST: &[UserHost] = &["]
for test in load("userhost-split.yaml"):
    atoms = test["atoms"]
    lines.append("    UserHost { source: %s, nick: %s, user: %s, host: %s }," % (
        rust_str(test["source"]), rust_str(atoms["nick"]), opt(atoms.get("user")),
        opt(atoms.get("host"))))
lines += ["];", ""]
OUTPUT.write_text("\n".join(lines))
print("wrote", OUTPUT)
